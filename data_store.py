def MC2D(X):
    y = torch.sin(X)
    y = torch.pow(y, 2)
    y = torch.prod(y, dim=1)
    y = torch.exp(y)
    return y

def ackley(X):
    y = -20 * torch.exp(-0.2*torch.sqrt((X**2).sum(1)/X.shape[1]))-\
        torch.exp(torch.cos(2*torch.pi*X).sum(1)/X.shape[1]) + \
        math.e + 20
    return -y

def mishra03(X):
    X1, X2 = X[:, 0], X[:, 1]
    return torch.sqrt(torch.abs(torch.cos(torch.sqrt(torch.abs(X1**2.0 + X2**2.0)))))+\
           0.01*(X1 + X2)

def levy(X):
    w = torch.zeros((X.shape[0], X.shape[1]))
    for i in range(1, X.shape[1] + 1):
        w[:, i - 1] = 1 + 1/4*(X[:, i-1] - 1)
    fval = (torch.sin(torch.pi*w[:, 0]))**2 + \
        ((w[:, X.shape[1]-1]-1)**2)*(1+(torch.sin(2*torch.pi*w[:, X.shape[1]-1]))**2)
    for i in range(1, X.shape[1]):
        fval += ((w[:, i]-1)**2)*(1+10*(torch.sin(torch.pi*w[:, i]))**2)
    return -fval

def alpine(X):
    temp = torch.abs(X*torch.sin(X) + 0.1*X)
    if len(temp.shape) <= 1:
        fval = torch.sum(temp)
    else:
        fval = torch.sum(temp, axis=1)
    return -fval

def rosenbrock(X):
    out = rosen(X.detach().cpu().numpy().T)
    return torch.from_numpy(out).to(X)

def sphere(X):
    out = torch.sum(X**2, dim=1)
    return out

def trid(X):
    out = torch.sum((X[:, :-1] - 1)**2, dim=-1) + torch.sum((X[:, 1:] - 1)**2, dim=-1)
    return out

